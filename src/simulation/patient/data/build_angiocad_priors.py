#!/usr/bin/env python3
"""Build src/simulation/patient/angiocadPriors.ts from the AngioCAD library index.

Source: Hosseini MS et al. AngioCAD: a publicly available X-ray angiography
dataset for coronary artery stenosis and CAD detection. Zenodo 2025.
https://doi.org/10.5281/zenodo.15826856 (CC BY 4.0).

Only tabular metadata is used (no pixels). Patients without an indication
(36 of 412; they also lack dominance) are excluded, so the conditioned table
has n = 376. Run from the repository root:

    python3 src/simulation/patient/data/build_angiocad_priors.py
"""
import json
import os

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", "..", "..", ".."))
SRC = os.path.join(ROOT, "datasets", "library", "angiocad", "index.json")
OUT = os.path.join(ROOT, "src", "simulation", "patient", "angiocadPriors.ts")

SEGMENTS = ["LM", "Prox LAD", "Mid LAD", "Dist LAD", "D1", "D2", "Prox LCx", "Mid LCx", "Dist LCx",
            "OM", "Prox RCA", "Mid RCA", "Dist RCA", "PDA", "PLB"]
GRADES = ["NL", "1-25", "26-50", "51-75", "76-90", "91-99", "100"]
INDICATIONS = ["SA", "UA", "NSTEMI", "STEMI"]


def main():
    d = json.load(open(SRC))
    patients = d["patients"]
    rows = []
    for p in patients:
        if not p.get("indication"):
            continue
        seg = p["segments"]
        g = "".join(str(GRADES.index(seg[s])) for s in SEGMENTS)
        age = int(p["age"]) if p.get("age") not in (None, "") else None
        lvef = int(p["lvef"].rstrip("%")) if p.get("lvef") else None
        flags = (1 if p.get("diabetes") else 0) | (2 if p.get("smoker") else 0) | (4 if p.get("hypertension") else 0) | (8 if p.get("dyslipidaemia") else 0)
        rows.append([p["id"], INDICATIONS.index(p["indication"]), age, p["sex"], lvef, "R" if p["dominance"] == "right" else "L", flags, g])

    n = len(rows)
    abnormal = [0] * len(SEGMENTS)
    by_ind = {k: {"n": 0, "abnormal": [0] * len(SEGMENTS)} for k in INDICATIONS}
    for r in rows:
        ind = INDICATIONS[r[1]]
        by_ind[ind]["n"] += 1
        for i, c in enumerate(r[7]):
            if c != "0":
                abnormal[i] += 1
                by_ind[ind]["abnormal"][i] += 1

    lines = []
    lines.append("// GENERATED by src/simulation/patient/data/build_angiocad_priors.py. Do not edit by hand.")
    lines.append("//")
    lines.append("// Tabular metadata from AngioCAD (Hosseini MS et al., Zenodo 2025,")
    lines.append("// https://doi.org/10.5281/zenodo.15826856, CC BY 4.0). Patients without an")
    lines.append(f"// indication are excluded: n = {n} of {len(patients)}. Grades per segment are coded")
    lines.append("// 0 NL, 1 '1-25', 2 '26-50', 3 '51-75', 4 '76-90', 5 '91-99', 6 '100' (percent diameter")
    lines.append("// stenosis bands as published). Flags: 1 diabetes, 2 smoker, 4 hypertension, 8 dyslipidaemia.")
    lines.append("")
    lines.append('export const ANGIOCAD_SOURCE = {')
    lines.append('  citation: ' + json.dumps(d["citation"]) + ',')
    lines.append('  doi: ' + json.dumps(d["doi"]) + ',')
    lines.append('  licence: ' + json.dumps(d["licence"]) + ',')
    lines.append(f'  nTotal: {len(patients)},')
    lines.append(f'  nWithIndication: {n},')
    lines.append('} as const;')
    lines.append("")
    lines.append("export const ANGIOCAD_SEGMENTS = " + json.dumps(SEGMENTS) + " as const;")
    lines.append("export type AngioCadSegment = (typeof ANGIOCAD_SEGMENTS)[number];")
    lines.append("export const ANGIOCAD_GRADES = " + json.dumps(GRADES) + " as const;")
    lines.append("export const ANGIOCAD_INDICATIONS = " + json.dumps(INDICATIONS) + " as const;")
    lines.append("export type AngioCadIndication = (typeof ANGIOCAD_INDICATIONS)[number];")
    lines.append("")
    lines.append("/** [id, indication index, age | null, sex, LVEF % | null, dominance, flags, grades] */")
    lines.append("export type AngioCadRow = [string, number, number | null, \"M\" | \"F\", number | null, \"R\" | \"L\", number, string];")
    lines.append("")
    lines.append("export const ANGIOCAD_ROWS: AngioCadRow[] = [")
    for r in rows:
        lines.append("  " + json.dumps(r).replace("null", "null") + ",")
    lines.append("];")
    lines.append("")
    lines.append("/** Abnormal (any grade other than NL) counts per segment, for tests and documentation. */")
    lines.append("export const ANGIOCAD_MARGINALS = {")
    lines.append(f"  all: {{ n: {n}, abnormal: {json.dumps(abnormal)} }},")
    for k in INDICATIONS:
        lines.append(f"  {k}: {{ n: {by_ind[k]['n']}, abnormal: {json.dumps(by_ind[k]['abnormal'])} }},")
    lines.append("} as const;")
    lines.append("")
    open(OUT, "w").write("\n".join(lines))
    print(f"wrote {OUT}: n = {n}")
    for i, s in enumerate(SEGMENTS):
        print(f"  {s:9s} abnormal {abnormal[i]:3d}/{n} = {100*abnormal[i]/n:5.1f}%")
    for k in INDICATIONS:
        print(k, by_ind[k]["n"])


if __name__ == "__main__":
    main()
